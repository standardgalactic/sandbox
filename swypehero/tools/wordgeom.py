#!/usr/bin/env python3
"""Reference word-geometry computations for the Swype Hero specification.

Generates LaTeX fragments (figure and tables) from the layout and metric
definitions given in Part VI. Everything printed in the specification as a
computed value comes from this script.

Usage: python3 wordgeom.py OUTDIR
"""
import math
import sys
from pathlib import Path

ROWS = ["qwertyuiop", "asdfghjkl", "zxcvbnm"]
OFFSETS = [0.0, 0.5, 1.5]      # row offsets in key widths (mobile layout)
PITCH = 1.3                    # vertical distance between row centres, key widths

CENTRES = {}
for r, (row, off) in enumerate(zip(ROWS, OFFSETS)):
    for i, ch in enumerate(row):
        CENTRES[ch] = (off + i + 0.5, r * PITCH + 0.5)


def collapse(word):
    out = []
    for ch in word:
        if not out or out[-1] != ch:
            out.append(ch)
    return out


def path(word):
    return [CENTRES[c] for c in collapse(word)]


def seg_len(a, b):
    return math.hypot(b[0] - a[0], b[1] - a[1])


def length(pts):
    return sum(seg_len(pts[i], pts[i + 1]) for i in range(len(pts) - 1))


def headings(pts):
    return [math.atan2(pts[i + 1][1] - pts[i][1], pts[i + 1][0] - pts[i][0])
            for i in range(len(pts) - 1)]


def wrap(a):
    while a > math.pi:
        a -= 2 * math.pi
    while a <= -math.pi:
        a += 2 * math.pi
    return a


def turning(pts):
    h = headings(pts)
    return [wrap(h[i + 1] - h[i]) for i in range(len(h) - 1)]


def orient(p, q, r):
    return (q[0] - p[0]) * (r[1] - p[1]) - (q[1] - p[1]) * (r[0] - p[0])


def proper_cross(a, b, c, d, eps=1e-9):
    o1, o2 = orient(a, b, c), orient(a, b, d)
    o3, o4 = orient(c, d, a), orient(c, d, b)
    return (o1 * o2 < -eps) and (o3 * o4 < -eps)


def crossings(pts):
    n = len(pts) - 1
    count = 0
    for i in range(n):
        for j in range(i + 2, n):
            if proper_cross(pts[i], pts[i + 1], pts[j], pts[j + 1]):
                count += 1
    return count


def reversals(pts, thresh=math.radians(150)):
    return sum(1 for t in turning(pts) if abs(t) >= thresh)


def resample_exact(pts, n):
    """Arc-length resampling by cumulative-distance interpolation."""
    cum = [0.0]
    for i in range(len(pts) - 1):
        cum.append(cum[-1] + seg_len(pts[i], pts[i + 1]))
    total = cum[-1]
    out = []
    j = 0
    for k in range(n):
        s = total * k / (n - 1)
        while j < len(pts) - 2 and cum[j + 1] < s:
            j += 1
        seg = cum[j + 1] - cum[j]
        t = 0 if seg == 0 else (s - cum[j]) / seg
        out.append((pts[j][0] + t * (pts[j + 1][0] - pts[j][0]),
                    pts[j][1] + t * (pts[j + 1][1] - pts[j][1])))
    return out


def loc_distance(w1, w2, n=32):
    a = resample_exact(path(w1), n)
    b = resample_exact(path(w2), n)
    return sum(seg_len(p, q) for p, q in zip(a, b)) / n


LEXICON = """
the and that have with this from they will would there their what about which when make like time just
know take people into year your good some could them other than then look only come over think also back
after use two how our work first well way even new want because any these give day most us it is be to of
in for on as at by or an we he she you his her not but all can had were said each tell does set three
word keyboard gesture typing balloon magic lizard quick pizza zebra minimum banana pretty queen quiz jazz
puppy eye pop level radar hello world water light sound thing great small large might right house point
place again where little much before through between under never always often while still every those
quiet quote output apple paper table chair green music story night field horse river stone cloud plant
swipe shape curve loop angle trace stroke finger screen touch play game score
""".split()


def metrics(word):
    p = path(word)
    return dict(
        word=word,
        letters=len(word),
        keys=len(p),
        L=length(p),
        T=sum(abs(t) for t in turning(p)),
        X=crossings(p),
        R=reversals(p),
    )


def pearson(xs, ys):
    n = len(xs)
    mx, my = sum(xs) / n, sum(ys) / n
    sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    sxx = sum((x - mx) ** 2 for x in xs)
    syy = sum((y - my) ** 2 for y in ys)
    return sxy / math.sqrt(sxx * syy)


def emit_keyboard_figure(words, scale_cm=1.25):
    lines = []
    lines.append("% generated by tools/wordgeom.py; do not edit by hand")
    lines.append("\\begin{figure}[t]")
    lines.append("\\centering")
    colors = ["blue!65!black", "red!70!black"]
    for idx, w in enumerate(words):
        lines.append("\\begin{tikzpicture}[x=%.3fcm,y=-%.3fcm]" % (scale_cm, scale_cm))
        for ch, (cx, cy) in CENTRES.items():
            lines.append(
                "\\draw[gray!60,rounded corners=1.2pt,line width=0.3pt] (%.3f,%.3f) rectangle (%.3f,%.3f);"
                % (cx - 0.46, cy - 0.46, cx + 0.46, cy + 0.46))
            lines.append("\\node[font=\\tiny\\sffamily,gray!70!black] at (%.3f,%.3f) {%s};" % (cx - 0.22, cy - 0.22, ch))
        p = path(w)
        coords = " -- ".join("(%.3f,%.3f)" % pt for pt in p)
        lines.append("\\draw[%s,line width=1.1pt,line cap=round,line join=round,-{Stealth[length=2.6mm]}] %s;" % (colors[idx % 2], coords))
        for pt in p:
            lines.append("\\fill[%s] (%.3f,%.3f) circle (0.06);" % (colors[idx % 2], pt[0], pt[1]))
        lines.append("\\fill[white,draw=%s,line width=0.8pt] (%.3f,%.3f) circle (0.11);" % (colors[idx % 2], p[0][0], p[0][1]))
        lines.append("\\end{tikzpicture}")
        m = metrics(w)
        lines.append("\\par\\smallskip{\\small\\textit{%s}: $L=%.2f$, $T/2\\pi=%.2f$, $X=%d$, $R=%d$.}\\par\\bigskip" % (
            w, m["L"], m["T"] / (2 * math.pi), m["X"], m["R"]))
    lines.append("\\caption{Idealized trajectories for \\textit{magic} (top) and \\textit{lizard} (bottom) on the default mobile QWERTY layout. The open circle marks the first key and the arrow marks the direction of traversal. Values of $L$ (path length in key widths), $T/2\\pi$ (total absolute turning in turns), $X$ (proper self-crossings) and $R$ (near-reversals) are computed by the reference definitions of Chapter~\\ref{ch:keyboard-geometry} and Chapter~\\ref{ch:complexity}.}")
    lines.append("\\label{fig:word-paths}")
    lines.append("\\end{figure}")
    return "\n".join(lines) + "\n"


def emit_metric_table(words):
    rows = []
    for w in words:
        m = metrics(w)
        rows.append("%s & %d & %d & %.2f & %.2f & %d & %d \\\\" % (
            w, m["letters"], m["keys"], m["L"], m["T"] / (2 * math.pi), m["X"], m["R"]))
    head = ("\\begin{table}[t]\n\\centering\n\\small\n\\begin{tabular}{lrrrrrr}\n\\toprule\n"
            "Word & Letters & Keys & $L$ & $T/2\\pi$ & $X$ & $R$ \\\\\n\\midrule\n")
    tail = ("\\bottomrule\n\\end{tabular}\n"
            "\\caption{Geometric measures of selected words on the default mobile QWERTY layout (Chapter~\\ref{ch:keyboard-geometry}). "
            "Letters is the length of the written word, Keys is the number of vertices after collapsing repeated letters, "
            "$L$ is path length in key widths, $T/2\\pi$ is total absolute turning in full turns, $X$ is the number of proper self-crossings and $R$ is the number of near-reversals (turns of at least $150^\\circ$).}\n"
            "\\label{tab:word-metrics}\n\\end{table}\n")
    return head + "\n".join(rows) + "\n" + tail


def main():
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    (out / "fig_word_paths.tex").write_text(emit_keyboard_figure(["magic", "lizard"]))
    table_words = ["the", "word", "magic", "lizard", "hello", "quick", "pizza", "banana", "minimum", "keyboard", "gesture", "typing"]
    (out / "tab_word_metrics.tex").write_text(emit_metric_table(table_words))

    lex = sorted(set(w for w in LEXICON if len(collapse(w)) >= 2 and all(c in CENTRES for c in w)))
    ms = [metrics(w) for w in lex]
    n = len(ms)
    letters = [m["letters"] for m in ms]
    r_L = pearson(letters, [m["L"] for m in ms])
    r_T = pearson(letters, [m["T"] for m in ms])
    r_X = pearson(letters, [m["X"] for m in ms])
    # closest pairs in location channel
    pairs = []
    for i in range(n):
        for j in range(i + 1, n):
            a, b = lex[i], lex[j]
            if abs(len(a) - len(b)) > 3:
                continue
            pairs.append((loc_distance(a, b), a, b))
    pairs.sort()
    rows = []
    for d, a, b in pairs[:10]:
        rows.append("%s & %s & %.3f \\\\" % (a, b, d))
    tab = ("\\begin{table}[t]\n\\centering\n\\small\n\\begin{tabular}{llr}\n\\toprule\nWord & Word & $d_{\\mathrm{loc}}$ \\\\\n\\midrule\n"
           + "\n".join(rows) +
           "\n\\bottomrule\n\\end{tabular}\n\\caption{The ten geometrically closest word pairs in the %d-word convenience sample of Chapter~\\ref{ch:word-ambiguity}, "
           "under the location-channel distance $d_{\\mathrm{loc}}$ (mean pointwise distance in key widths between 32-point arc-length resamplings of the idealized paths; pairs whose letter counts differ by more than three are not compared).}\n"
           "\\label{tab:closest-pairs}\n\\end{table}\n" % n)
    (out / "tab_closest_pairs.tex").write_text(tab)
    stats = (
        "%% generated by tools/wordgeom.py\n"
        "\\newcommand{\\lexN}{%d}\n"
        "\\newcommand{\\rLettersL}{%.2f}\n"
        "\\newcommand{\\rLettersT}{%.2f}\n"
        "\\newcommand{\\rLettersX}{%.2f}\n" % (n, r_L, r_T, r_X)
    )
    (out / "stats.tex").write_text(stats)
    print("words:", n, "r(L)=%.3f r(T)=%.3f r(X)=%.3f" % (r_L, r_T, r_X))
    for d, a, b in pairs[:10]:
        print("%.3f %s %s" % (d, a, b))
    for w in ["magic", "lizard", "hello", "banana", "pizza", "minimum"]:
        print(metrics(w))


if __name__ == "__main__":
    main()
